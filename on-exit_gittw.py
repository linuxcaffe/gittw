#!/usr/bin/env python3
"""on-exit_gittw.py — auto-commit ~/.task/ after every Taskwarrior write operation.

Install: tw -I gittw   (or: ln -s ~/dev/gittw/on-exit_gittw.py ~/.task/hooks/ && chmod +x …)
Off:     gittw.autocommit = no  in ~/.task/config/gittw.rc, or hook-ctrl (chmod -x).
"""
import os as _os_timing, time as _time_module
if _os_timing.environ.get('TW_TIMING'):
    import atexit as _atexit
    _t0 = _time_module.perf_counter()

    def _report_timing(_f=__file__):
        elapsed = (_time_module.perf_counter() - _t0) * 1000
        import os.path as _osp
        print(f"[timing] {_osp.basename(_f)}: {elapsed:.1f}ms", file=__import__('sys').stderr)

    _atexit.register(_report_timing)


# ============================================================================
# DEBUG VERSION - Auto-generated by make-awesome.py
# ============================================================================

import os
import sys
from pathlib import Path
from datetime import datetime
import json
# Read stdin first — empty means read-only operation (export, next, list, etc.): skip.
# Doing this before any heavy imports keeps passthrough cost minimal (~sys+json only).

# Debug configuration (default 0, triggered by tw --debug=2)
DEBUG_MODE = 0

tw_debug_level = os.environ.get('TW_DEBUG', '0')
try:
    tw_debug_level = int(tw_debug_level)
except ValueError:
    tw_debug_level = 0

debug_active = DEBUG_MODE == 1 or tw_debug_level >= 2

def get_log_dir():
    """Log dir respects TW_TASK_DIR for dev/test isolation."""
    import os as _os
    task_dir = Path(_os.environ.get('TW_TASK_DIR', str(Path.home() / '.task')))
    log_dir = task_dir / 'logs' / 'debug'
    log_dir.mkdir(parents=True, exist_ok=True)
    return log_dir

if debug_active:
    DEBUG_LOG_DIR = get_log_dir()
    DEBUG_SESSION_ID = datetime.now().strftime("%Y%m%d_%H%M%S")
    try:
        script_name = Path(__file__).stem
    except:
        script_name = Path(sys.argv[0]).stem if sys.argv else "script"
    DEBUG_LOG_FILE = DEBUG_LOG_DIR / f"{script_name}_debug_{DEBUG_SESSION_ID}.log"
    
    def debug_log(message, level=1):
        if debug_active and tw_debug_level >= level:
            timestamp = datetime.now().strftime("%H:%M:%S.%f")[:-3]
            log_line = f"{timestamp} [DEBUG-{level}] {message}\n"
            with open(DEBUG_LOG_FILE, "a") as f:
                f.write(log_line)
            print(f"\033[34m[DEBUG-{level}]\033[0m {message}", file=sys.stderr)
    
    with open(DEBUG_LOG_FILE, "w") as f:
        f.write("=" * 70 + "\n")
        f.write(f"Debug Session - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write(f"Script: {script_name}\n")
        f.write(f"TW_DEBUG Level: {tw_debug_level}\n")
        f.write("=" * 70 + "\n\n")
    debug_log(f"Debug logging initialized: {DEBUG_LOG_FILE}", 1)
else:
    def debug_log(message, level=1):
        pass

# ============================================================================
# Original Code
# ============================================================================

tasks = []
for line in sys.stdin:
    line = line.strip()
    if line:
        try:
            tasks.append(json.loads(line))
        except json.JSONDecodeError:
            pass

if not tasks:
    sys.exit(0)

# Write operation confirmed — now import heavier modules
import os
import subprocess
from pathlib import Path

task_dir = Path(os.environ.get('TW_TASK_DIR', Path.home() / '.task'))

if not (task_dir / '.git').exists():
    sys.exit(0)


def autocommit_enabled():
    """gittw.autocommit in config/gittw.rc; read directly, since calling `task` from a hook is slow."""
    try:
        for line in (task_dir / 'config' / 'gittw.rc').read_text().splitlines():
            key, sep, value = line.split('#', 1)[0].partition('=')
            if sep and key.strip() == 'gittw.autocommit':
                return value.strip().lower() not in ('no', 'off', 'false', '0')
    except OSError:
        pass
    return True


def station():
    """gittw.device in local.rc (this station's name), else the hostname."""
    try:
        for line in (task_dir / 'local.rc').read_text().splitlines():
            key, sep, value = line.split('#', 1)[0].partition('=')
            if sep and key.strip() == 'gittw.device' and value.strip():
                return value.strip()
    except OSError:
        pass
    import socket
    return socket.gethostname().split('.')[0] or 'unknown'


if not autocommit_enabled():
    sys.exit(0)

try:
    # Bail if git is mid-operation (merge, rebase, cherry-pick)
    for sentinel in ('MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REBASE_HEAD', 'rebase-merge', 'rebase-apply'):
        if (task_dir / '.git' / sentinel).exists():
            sys.exit(0)

    result = subprocess.run(
        ['git', '-C', str(task_dir), 'status', '--porcelain'],
        capture_output=True, text=True
    )
    if not result.stdout.strip():
        sys.exit(0)

    descs = [t.get('description', '')[:50] for t in tasks[:3]]
    message = 'task: ' + '; '.join(d for d in descs if d)
    message += f'\n\nStation: {station()}'

    subprocess.run(['git', '-C', str(task_dir), 'add', '-A'], capture_output=True)
    subprocess.run(['git', '-C', str(task_dir), 'commit', '-m', message], capture_output=True)
except Exception:
    pass  # Never let gittw failures surface to Taskwarrior
